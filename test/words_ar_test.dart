import 'package:ak_system/data/words.dart';
import 'package:ak_system/l10n/lang.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  String ar(double v) => dollarsInWords(v, AppLang.ar);

  test('English stays the default', () {
    expect(dollarsInWords(2500), 'Two thousand five hundred US dollars');
    expect(dollarsInWords(1, AppLang.en), 'One US dollar');
  });

  test('one, two, three to ten, eleven and up', () {
    expect(ar(1), 'فقط دولار أميركي واحد لا غير');
    expect(ar(2), 'فقط دولاران أميركيان لا غير');
    expect(ar(3), 'فقط ثلاثة دولارات أميركية لا غير');
    expect(ar(10), 'فقط عشرة دولارات أميركية لا غير');
    expect(ar(11), 'فقط أحد عشر دولاراً أميركياً لا غير');
    expect(ar(12), 'فقط اثنا عشر دولاراً أميركياً لا غير');
    expect(ar(25), 'فقط خمسة وعشرون دولاراً أميركياً لا غير');
    expect(ar(99), 'فقط تسعة وتسعون دولاراً أميركياً لا غير');
  });

  test('hundreds', () {
    expect(ar(100), 'فقط مئة دولار أميركي لا غير');
    expect(ar(200), 'فقط مئتا دولار أميركي لا غير');
    expect(ar(250), 'فقط مئتان وخمسون دولاراً أميركياً لا غير');
    expect(ar(103), 'فقط مئة وثلاثة دولارات أميركية لا غير');
    expect(ar(111), 'فقط مئة وأحد عشر دولاراً أميركياً لا غير');
    expect(ar(800), 'فقط ثمانمئة دولار أميركي لا غير');
  });

  test('thousands', () {
    expect(ar(1000), 'فقط ألف دولار أميركي لا غير');
    expect(ar(2000), 'فقط ألفا دولار أميركي لا غير');
    expect(ar(2500), 'فقط ألفان وخمسمئة دولار أميركي لا غير');
    expect(ar(3000), 'فقط ثلاثة آلاف دولار أميركي لا غير');
    expect(ar(8000), 'فقط ثمانية آلاف دولار أميركي لا غير');
    expect(ar(10000), 'فقط عشرة آلاف دولار أميركي لا غير');
    expect(ar(11000), 'فقط أحد عشر ألف دولار أميركي لا غير');
    expect(ar(11500), 'فقط أحد عشر ألفاً وخمسمئة دولار أميركي لا غير');
    expect(ar(1200), 'فقط ألف ومئتا دولار أميركي لا غير');
    expect(ar(100000), 'فقط مئة ألف دولار أميركي لا غير');
    expect(ar(200000), 'فقط مئتا ألف دولار أميركي لا غير');
  });

  test('millions', () {
    expect(ar(1000000), 'فقط مليون دولار أميركي لا غير');
    expect(ar(2000000), 'فقط مليونا دولار أميركي لا غير');
    expect(ar(3000000), 'فقط ثلاثة ملايين دولار أميركي لا غير');
    expect(ar(2000500), 'فقط مليونان وخمسمئة دولار أميركي لا غير');
    expect(
      ar(1234567),
      'فقط مليون ومئتان وأربعة وثلاثون ألفاً وخمسمئة وسبعة وستون '
      'دولاراً أميركياً لا غير',
    );
  });

  test('cents', () {
    expect(ar(1500.50), 'فقط ألف وخمسمئة دولار أميركي وخمسون سنتاً لا غير');
    expect(
      ar(1021.5),
      'فقط ألف وواحد وعشرون دولاراً أميركياً وخمسون سنتاً لا غير',
    );
    expect(ar(5.01), 'فقط خمسة دولارات أميركية وسنت واحد لا غير');
    expect(ar(12000.02), 'فقط اثنا عشر ألف دولار أميركي وسنتان لا غير');
    expect(ar(0.75), 'فقط خمسة وسبعون سنتاً لا غير');
    expect(ar(0.07), 'فقط سبعة سنتات لا غير');
  });
}
